from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Cm, Pt

doc = Document()

# ตั้งค่าขนาดกระดาษ A4 และปรับระยะขอบบน-ล่างให้แคบลงเล็กน้อยเพื่อให้พอดีหน้าเดียว
section = doc.sections[0]
section.page_width = Cm(21.0)
section.page_height = Cm(29.7)
section.top_margin = Cm(1.5)
section.bottom_margin = Cm(1.5)
section.left_margin = Cm(2.0)
section.right_margin = Cm(2.0)

# ตั้งค่าฟอนต์เริ่มต้นเป็น TH Sarabun PSK ขนาด 15 pt (ลดจาก 16 เพื่อให้ไม่ล้นหน้า)
style = doc.styles['Normal']
font = style.font
font.name = 'TH Sarabun PSK'
font.size = Pt(15)

# ฟังก์ชันช่วยเพิ่มข้อความพร้อมกำหนดระยะห่างหลังบรรทัด (space_after) ให้กระชับ
def add_p(
    text='',
    align=WD_ALIGN_PARAGRAPH.LEFT,
    bold=False,
    size=15,
    space_after=2,
):
  p = doc.add_paragraph()
  p.alignment = align
  p.paragraph_format.space_after = Pt(space_after)
  p.paragraph_format.line_spacing = 1.0
  if text:
    run = p.add_run(text)
    run.bold = bold
    run.font.size = Pt(size)
  return p


# ส่วนหัวข้อ "แบบ 3" (ชิดขวา)
p_head = add_p(align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=0)
r_head = p_head.add_run('แบบ 3')
r_head.bold = True

